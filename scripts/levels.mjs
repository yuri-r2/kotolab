// Precomputes each library song's difficulty for the arrangement the app
// shows by default (same choice as when a song is opened), so the library
// can be ordered by level without arranging 50 songs in the browser.
//
//   node scripts/levels.mjs   → js/song-levels.js

import { writeFileSync } from 'node:fs';
import { SONGS } from '../js/songs.js';
import { songDifficulty } from '../js/difficulty.js';

const levels = {};
for (const s of SONGS) levels[s.id] = songDifficulty(s);
const sorted = Object.entries(levels).sort((a, b) => a[1].difficulty - b[1].difficulty);
for (const [id, l] of sorted) console.log(String(l.difficulty).padStart(4), 'L' + l.level, id);
writeFileSync(new URL('../js/song-levels.js', import.meta.url),
  `// Generated by scripts/levels.mjs — do not edit by hand.\nexport const SONG_LEVELS = ${JSON.stringify(levels, null, 1)};\n`);
